//go:build windows

package mbvip

import (
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"time"
)

const genHeader = "// Code generated by mbvip bindgen. DO NOT EDIT.\n"

type genMethod struct {
	Name   string
	Params []string
	Return string
}

// GenerateBindings reflects the bound structs and writes Wails-style JS/TS
// wrappers into dir (one file per binding plus an index).
func GenerateBindings(dir string, bindings []Binding) error {
	if len(bindings) == 0 {
		return fmt.Errorf("mbvip: no bindings to generate")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	names := make([]string, 0, len(bindings))
	for _, b := range bindings {
		if b.Name == "" {
			return fmt.Errorf("mbvip: binding name is empty")
		}
		methods, err := reflectMethods(b.Target)
		if err != nil {
			return fmt.Errorf("mbvip: %s: %w", b.Name, err)
		}
		if err := writeBindingFiles(dir, b.Name, methods); err != nil {
			return err
		}
		names = append(names, b.Name)
	}
	return writeIndex(dir, names)
}

func reflectMethods(target any) ([]genMethod, error) {
	methods, err := bindingMethods(target)
	if err != nil {
		return nil, err
	}
	var out []genMethod
	for _, m := range methods {
		mt := m.Type
		gm := genMethod{Name: m.Name, Return: tsReturn(mt)}
		// mt.In(0) is the receiver
		for j := 1; j < mt.NumIn(); j++ {
			gm.Params = append(gm.Params, tsType(mt.In(j)))
		}
		out = append(out, gm)
	}
	return out, nil
}

var timeType = reflect.TypeOf(time.Time{})

func tsReturn(mt reflect.Type) string {
	n := mt.NumOut()
	if n > 0 && mt.Out(n-1) == errType {
		n--
	}
	switch n {
	case 0:
		return "void"
	case 1:
		return tsType(mt.Out(0))
	default:
		parts := make([]string, n)
		for i := 0; i < n; i++ {
			parts[i] = tsType(mt.Out(i))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
}

func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "string"
		}
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<" + tsType(t.Key()) + ", " + tsType(t.Elem()) + ">"
	case reflect.Ptr:
		return tsType(t.Elem())
	case reflect.Struct:
		if t == timeType {
			return "string"
		}
		return "any"
	default:
		return "any"
	}
}

func writeBindingFiles(dir, name string, methods []genMethod) error {
	var js, dts strings.Builder
	js.WriteString(genHeader)
	js.WriteString("\n")
	dts.WriteString(genHeader)
	dts.WriteString("\n")

	for _, m := range methods {
		args := make([]string, len(m.Params))
		for i := range m.Params {
			args[i] = fmt.Sprintf("arg%d", i+1)
		}
		call := fmt.Sprintf("window.__mbInvoke(%q", name+"."+m.Name)
		if len(args) > 0 {
			call += ", " + strings.Join(args, ", ")
		}
		call += ")"
		fmt.Fprintf(&js, "export function %s(%s) {\n  return %s\n}\n\n",
			m.Name, strings.Join(args, ", "), call)

		tsParams := make([]string, len(m.Params))
		for i, p := range m.Params {
			tsParams[i] = fmt.Sprintf("arg%d: %s", i+1, p)
		}
		fmt.Fprintf(&dts, "export function %s(%s): Promise<%s>\n",
			m.Name, strings.Join(tsParams, ", "), m.Return)
	}

	if err := os.WriteFile(filepath.Join(dir, name+".js"), []byte(js.String()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, name+".d.ts"), []byte(dts.String()), 0o644)
}

func writeIndex(dir string, names []string) error {
	sort.Strings(names)
	var js, dts strings.Builder
	js.WriteString(genHeader)
	js.WriteString("\n")
	dts.WriteString(genHeader)
	dts.WriteString("\n")
	for _, n := range names {
		fmt.Fprintf(&js, "export * as %s from './%s.js'\n", n, n)
		fmt.Fprintf(&dts, "export * as %s from './%s'\n", n, n)
	}
	if err := os.WriteFile(filepath.Join(dir, "index.js"), []byte(js.String()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "index.d.ts"), []byte(dts.String()), 0o644)
}
